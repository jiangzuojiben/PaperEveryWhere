import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Keep this bounded catalog as plain SVG data so plugins do not need React.
const names = 'flask-conical dices dice-5 star settings file file-text folder book-open search plus minus pencil check x refresh-cw blocks table calendar clock link code globe arrow-left arrow-right chevron-down chevron-right eye trash download upload circle-help bell clipboard terminal sparkles layout-dashboard columns-2 panels-top-left bookmark heart house menu lightbulb list git-branch zap external-link puzzle'.split(' ');
const base = new URL('../node_modules/lucide-react/', import.meta.url), icons = {};
for (const name of names) {
  const source = await readFile(new URL(`dist/esm/icons/${name}.js`, base), 'utf8');
  const match = source.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/);
  if (!match) throw new Error('Cannot extract static Lucide data: ' + name);
  const data = match[1].replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":');
  icons[name] = JSON.parse(data).map(([tag, attributes]) => [tag, Object.fromEntries(Object.entries(attributes).filter(([key]) => key !== 'key'))]);
}
const license = await readFile(new URL('LICENSE', base), 'utf8');
const output = new URL('../app/plugin-icon-data.mjs', import.meta.url);
await writeFile(output, `/* Generated by scripts/generate-plugin-icons.mjs from lucide-react 0.468.0.\n${license.replaceAll('*/', '* /')}\n*/\nexport default ${JSON.stringify(icons)};\n`);
console.log(`Wrote ${Object.keys(icons).length} static icons to ${fileURLToPath(output)}`);
